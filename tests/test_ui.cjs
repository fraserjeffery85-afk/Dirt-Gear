const {chromium}=require('playwright');const fs=require('fs');
const SP=process.argv[2];const s=JSON.parse(fs.readFileSync(SP+'/session.json'));
(async()=>{const b=await chromium.launch({args:['--use-gl=swiftshader','--enable-unsafe-swiftshader']});const p=await b.newPage({viewport:{width:1500,height:920}});
const errs=[];p.on('pageerror',e=>errs.push('pageerror '+e.message));p.on('console',m=>{if(m.type()==='error')errs.push('console '+m.text())});
await p.goto(s.url);await p.waitForTimeout(1200);await p.screenshot({path:SP+'/shots/1-empty.png'});
await p.setInputFiles('#psdInput',SP+'/fixtures/test-gear.psd');
await p.waitForSelector('#canvas:not([hidden])',{timeout:60000});await p.waitForTimeout(1500);
await p.screenshot({path:SP+'/shots/2-open.png'});
await p.click('#addName');await p.waitForSelector('#textDialog[open]');await p.fill('#textValue','JEFFERY');await p.waitForTimeout(1500);
await p.screenshot({path:SP+'/shots/3-text.png'});
await p.click('#applyText');await p.waitForFunction(()=>!document.getElementById('busyDialog').open,{timeout:30000});await p.waitForTimeout(2500);
await p.click('#addNumber');await p.waitForSelector('#textDialog[open]');await p.check('#useGradient');await p.waitForTimeout(1000);
await p.screenshot({path:SP+'/shots/4-number-dialog.png'});
await p.click('#applyText');await p.waitForFunction(()=>!document.getElementById('busyDialog').open,{timeout:30000});await p.waitForTimeout(3000);
await p.click('.advanced-controls summary');
await p.screenshot({path:SP+'/shots/5-edit.png'});
await p.click('#open3d');await p.waitForTimeout(6000);await p.screenshot({path:SP+'/shots/6-3d.png'});await p.click('#close3d');
await p.click('[data-view=normal]');await p.waitForTimeout(2500);await p.screenshot({path:SP+'/shots/7-norm.png'});
await p.setViewportSize({width:1100,height:760});await p.click('[data-view=default]');await p.waitForTimeout(1500);await p.screenshot({path:SP+'/shots/8-small.png'});
console.log(JSON.stringify(errs,null,1));await b.close()})().catch(e=>{console.error(e);process.exit(1)});
