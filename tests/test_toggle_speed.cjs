const {chromium}=require('playwright');const fs=require('fs');
const SP=process.argv[2],PSD=process.argv[3];const s=JSON.parse(fs.readFileSync(SP+'/session.json'));
const ok=(c,m)=>{if(!c)throw Error('FAIL '+m);console.log('PASS',m)};
(async()=>{const b=await chromium.launch();const p=await b.newPage({viewport:{width:1500,height:920}});
const errs=[];p.on('pageerror',e=>errs.push(e.message));
await p.goto(s.url);await p.waitForTimeout(800);
let t=Date.now();await p.setInputFiles('#psdInput',PSD);await p.waitForSelector('#canvas:not([hidden])',{timeout:300000});
await p.waitForFunction(()=>ready&&images.default&&!document.getElementById('busyDialog').open,null,{timeout:300000});console.log('open+first preview',(Date.now()-t)/1000,'s');
let modal=false;await p.exposeFunction('sawModal',()=>{modal=true});
await p.evaluate(()=>{new MutationObserver(()=>{if(document.getElementById('busyDialog').open)window.sawModal()}).observe(document.getElementById('busyDialog'),{attributes:true})});
const before=await p.evaluate(()=>images.default.src);
const eyes=p.locator('.layer input[type=checkbox]:not(:disabled)');const n=await eyes.count();
t=Date.now();for(const i of [n-1,n-2,n-3])await eyes.nth(i).click();
ok(await p.locator('#canvasStatus').textContent()==='Updating preview…','status shows Updating preview while toggling');
await p.waitForFunction(b=>images.default&&images.default.src!==b&&!visBusy&&!visTimer,before,{timeout:120000});
console.log('3 rapid toggles → preview updated in',(Date.now()-t)/1000,'s');
ok(!modal,'no blocking dialog during layer toggles');
ok((await p.locator('.layer.off').count())>=3,'rows dimmed immediately');
await p.waitForTimeout(500);await p.screenshot({path:SP+'/shots/toggle.png'});
ok(errs.length===0,'no page errors '+JSON.stringify(errs));await b.close()})().catch(e=>{console.error(e.message);process.exit(1)});
